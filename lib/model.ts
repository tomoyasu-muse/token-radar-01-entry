// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token protocols below the floor with the strongest implied value, not merely the biggest TVL:
// the early rows the radar exists to find. A protocol is pre-token when its index entry records no
// token (no market cap, no CoinGecko id, no symbol); the snapshot's live-token protocols are kept
// apart and shown with the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, in five steps any reader can check:
//
//   tier multiple  TVL tier: under $100M 0.45, $100M-$1B 0.32, over $1B 0.22.
//                  A launch multiple compresses as TVL grows: the biggest protocols have the
//                  least upside left per dollar locked, the smallest the most.
//   growth         clamp(change_7d, -60, 120) per cent. Gains count at 0.7, losses at 1.0:
//                  a falling TVL hurts a launch case more than a rising one helps it.
//   maturity       0.55 + 0.45 * sqrt(min(age_days, 1095) / 1095). Age is the time since the
//                  protocol was first listed: the best record of how long it has run with no
//                  token. The square root rewards survival early and saturates: a protocol that
//                  has run two tokenless years is seasoned, a third adds little.
//                  Unknown age uses 365 days.
//   breadth        1 + 0.04 * min(chains - 1, 4): a protocol live on several chains has more
//                  distribution for a launch than a single-chain one, capped at 1.16.
//   category       Fee-bearing categories launch dearer than pipes: Dexs and Lending 1.08,
//                  Yield and Derivatives 1.06, CDP, RWA, curators and collateral markets 1.04,
//                  everything else 1.00, Payments 0.97, Chains 0.95, bridges 0.92.
//
//   implied = max(1, round(tvl_usd x tier x growthMult x maturityMult x breadthMult x categoryMult))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard's
// detail view shows each multiplier so a reader can audit any rank.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

